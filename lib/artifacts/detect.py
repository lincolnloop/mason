"""Configuration values worked out from the project's repository, so the file can leave them out.

Each function reads only what git tracks (plus the project's own `.env`), and returns nothing
rather than guessing when the repository doesn't say. A value that can't be detected has to be
set in the project's `mason.toml`; `project.resolve` reports which.
"""

import json
import re
import subprocess
from pathlib import Path, PurePosixPath

# The first lines pip-compile and `uv pip compile` write into a compiled requirements file.
PIP_COMPILE_MARKERS = ('autogenerated by pip-compile', 'autogenerated by uv via')
GITHUB_REMOTE = re.compile(
    r'^(?:git@github\.com:|ssh://git@github\.com/|https://github\.com/)'
    r'([A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+?)(?:\.git)?/?$'
)
# Lockfiles the dependency readers don't parse. Their presence is reported, not ignored.
UNSUPPORTED_LOCKFILES = ('uv.lock', 'poetry.lock', 'Pipfile.lock', 'yarn.lock', 'pnpm-lock.yaml')


def _git(project: Path, *args: str) -> str | None:
    result = subprocess.run(['git', '-C', str(project), *args], capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else None


def tracked_files(project: Path) -> list[str]:
    return (_git(project, 'ls-files') or '').splitlines()


def repo_name(project: Path) -> str | None:
    """`owner/repo` from the origin remote, if it is on GitHub."""
    url = _git(project, 'remote', 'get-url', 'origin')
    match = GITHUB_REMOTE.match(url or '')
    return match.group(1) if match else None


def main_branch(project: Path) -> str | None:
    """The branch origin/HEAD points at (set by clone, or `git remote set-head origin --auto`)."""
    ref = _git(project, 'symbolic-ref', '--short', 'refs/remotes/origin/HEAD')
    if ref and ref.startswith('origin/'):
        return ref.removeprefix('origin/')
    return None


def is_compiled(text: str) -> bool:
    header = text.splitlines()[:12]
    return any(marker in line for line in header for marker in PIP_COMPILE_MARKERS)


def header_command(text: str) -> str | None:
    """The command a compiled requirements file's header says produced it."""
    header = text.splitlines()[:12]
    for index, line in enumerate(header):
        if 'following command' in line:
            for following in header[index + 1 :]:
                # Some tools write the command as a shell prompt: '#    $ make requirements'.
                command = following.lstrip('#').strip().removeprefix('$ ').strip()
                if command:
                    return command
    return None


def pip(project: Path, files: list[str]) -> dict[str, object]:
    """Compiled requirements files, their sources, and the command that recompiles them."""
    requirements, sources, commands = [], [], []
    for path in files:
        if not path.endswith('.txt') or not (project / path).is_file():
            continue
        try:
            text = (project / path).read_text(encoding='utf-8')
        except (OSError, UnicodeDecodeError):
            continue
        if not is_compiled(text):
            continue
        requirements.append(path)
        source = path.removesuffix('.txt') + '.in'
        if source in files:
            sources.append(source)
        command = header_command(text)
        if command and command not in commands:
            commands.append(command)
    found: dict[str, object] = {}
    if requirements:
        found['pip_requirements'] = requirements
        found['pip_sources'] = sources
    if commands:
        # pip-compile keeps existing pins unless asked to upgrade, so running every file's
        # command recompiles only what a changed source requires.
        found['pip_compile'] = ' && '.join(commands)
    return found


def npm(project: Path, files: list[str]) -> dict[str, object]:
    """Directories with a tracked package-lock.json, and whether any of them has a build."""
    projects = []
    for path in files:
        posix = PurePosixPath(path)
        if posix.name == 'package-lock.json' and 'node_modules' not in posix.parts:
            projects.append(str(posix.parent))  # '.' for the repository root
    found: dict[str, object] = {}
    if projects:
        found['npm_projects'] = projects
        if any(_has_build_script(project / directory) for directory in projects):
            found['npm_build'] = 'npm run build'
    return found


def _has_build_script(directory: Path) -> bool:
    try:
        manifest = json.loads((directory / 'package.json').read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return False
    return isinstance(manifest, dict) and 'build' in (manifest.get('scripts') or {})


def worktree_copy(project: Path) -> list[str]:
    """`.env`, if the project has one that git ignores: a fresh worktree won't have it."""
    if (project / '.env').is_file() and _git(project, 'check-ignore', '-q', '.env') is not None:
        return ['.env']
    return []


# Where a project keeps its own coding conventions, for people and agents alike.
CONVENTIONS_PATHS = ('docs/conventions.md', 'CONVENTIONS.md', 'docs/CONVENTIONS.md')


def conventions(files: list[str]) -> list[str]:
    """The project's conventions document, if it has one at a usual path."""
    tracked = set(files)
    return [path for path in CONVENTIONS_PATHS if path in tracked]


def ci_config(files: list[str]) -> str | None:
    """The CI configuration that runs on pull requests, if the repository has one."""
    for path in files:
        if path == '.circleci/config.yml' or (
            path.startswith('.github/workflows/') and path.endswith(('.yml', '.yaml'))
        ):
            return path
    return None


def project_key(project: Path) -> str:
    """The name a project's runs and locks are kept under: its GitHub repository, so two
    checkouts with the same directory name in different organisations stay apart."""
    name = repo_name(project)
    return name.replace('/', '__') if name else project.resolve().name


def unsupported_lockfiles(files: list[str]) -> list[str]:
    return [path for path in files if PurePosixPath(path).name in UNSUPPORTED_LOCKFILES]
