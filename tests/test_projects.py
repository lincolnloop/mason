def make_clone(repo: str, directory: Path) -> str:
    """What `gh repo clone` leaves: a repository with an origin remote and origin/HEAD."""
    if (directory / '.git').exists():
        return f'fetched {repo}'
    git = ['git', '-C', str(directory), '-c', 'user.name=t', '-c', 'user.email=t@example.com']
    subprocess.run(['git', 'init', '-q', '-b', 'main', str(directory)], check=True)
    subprocess.run([*git, 'remote', 'add', 'origin', f'git@github.com:{repo}.git'], check=True)
    (directory / 'requirements.in').write_text('django\n')
    (directory / 'requirements.txt').write_text(
        '#\n# This file is autogenerated by pip-compile with Python 3.12\n'
        '# by the following command:\n#\n#    pip-compile requirements.in\n#\ndjango==5.2\n'
    )
    subprocess.run([*git, 'add', '.'], check=True)
    subprocess.run([*git, 'commit', '-q', '-m', 'base'], check=True)
    subprocess.run([*git, 'update-ref', 'refs/remotes/origin/main', 'HEAD'], check=True)
    subprocess.run(
        [*git, 'symbolic-ref', 'refs/remotes/origin/HEAD', 'refs/remotes/origin/main'], check=True
    )
    return f'cloned {repo}'


class FakeGh:
    """gh, answering the calls `project add` makes."""

    def __init__(
        self,
        push: bool = True,
        discussions: bool = True,
        alerts: bool = True,
        label: bool = False,
        label_create_fails: bool = False,
    ) -> None:
        self.push, self.discussions, self.alerts, self.label = push, discussions, alerts, label
        self.label_create_fails = label_create_fails
        self.calls: list[list[str]] = []

    def __call__(self, args: Sequence[str]) -> tuple[int, str, str]:
        args = list(args)
        self.calls.append(args)
        if args[:2] == ['api', f'repos/{REPO}']:
            data = {'permissions': {'push': self.push}, 'has_discussions': self.discussions}
            return 0, json.dumps(data), ''
        if args[0] == 'api' and 'dependabot/alerts' in args[1]:
            return (0, '[]', '') if self.alerts else (1, '', 'HTTP 403: Resource not accessible\n')
        if args[:2] == ['label', 'list']:
            return 0, 'automation\n' if self.label else '', ''
        if args[:2] == ['label', 'create']:
            return (1, '', 'HTTP 403') if self.label_create_fails else (0, '', '')
        raise AssertionError(f'unexpected gh call: {args}')


