GH_SCRIPT = """#!/bin/sh
echo "$*" >> "{record}"
case "$1 $2" in
  "repo clone")
    git init -q -b main "$4" && git -C "$4" remote add origin "git@github.com:$3.git" ;;
  "api repos/o/app") echo '{{"permissions": {{"push": true}}, "has_discussions": false}}' ;;
  "api repos/o/app/dependabot/alerts?per_page=1") echo '[]' ;;
  "label list") ;;
  "label create") ;;
  *) echo "unexpected: $*" >&2; exit 9 ;;
esac
"""


class CliTests(unittest.TestCase):
    """`mason project add` and `mason run` through the command line, with a fake gh."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        bin_dir = Path(self._tmp.name)
        self.record = bin_dir / 'calls'
        fake = bin_dir / 'gh'
        fake.write_text(GH_SCRIPT.format(record=self.record))
        fake.chmod(fake.stat().st_mode | stat.S_IEXEC)
        self.env = dict(os.environ, PATH=f'{bin_dir}:{os.environ["PATH"]}')

    def tearDown(self) -> None:
        self._tmp.cleanup()
        shutil.rmtree(paths.config_home(), ignore_errors=True)
        shutil.rmtree(paths.cache_home(), ignore_errors=True)

    def mason(self, *args: str, stdin: str = '') -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, '-I', str(ROOT / 'bin' / 'artifact'), *args],
            capture_output=True,
            text=True,
            input=stdin,
            env=self.env,
            check=False,
        )

    def test_add_without_asking(self) -> None:
        result = self.mason('project', 'add', REPO, '--workflow', 'dependency-report', '--yes')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('Added o/app', result.stdout)
        self.assertIn('Discussions are turned off', result.stderr)
        self.assertIn('label create automation --repo o/app', self.record.read_text())
        self.assertEqual(project.enabled_workflows(REPO), ['dependency-report'])

        result = self.mason('run', 'code-review', '--repo', REPO, '--pr', '1', '--dry-run')
        self.assertEqual(result.returncode, 1)
        self.assertIn('code-review is not enabled for o/app', result.stderr)
        result = self.mason('run', 'dependency-report', '--repo', REPO, '--dry-run')
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_asks_which_workflows_then_to_go_ahead(self) -> None:
        result = self.mason('project', 'add', REPO, stdin='code-review\nn\n')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('Workflows: code-review', result.stderr)
        self.assertEqual(result.stdout, 'Nothing written.\n')
        self.assertFalse(paths.settings(REPO).exists())

        shutil.rmtree(paths.clone(REPO))  # or the second run fetches it from GitHub
        result = self.mason('project', 'add', REPO, stdin='\ny\n')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(project.enabled_workflows(REPO), sorted(runner.WORKFLOWS))

    def test_dry_run_and_no_answer(self) -> None:
        result = self.mason('project', 'add', REPO, '--workflow', 'code-review', '--dry-run')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertNotIn('label create', self.record.read_text())
        self.assertFalse(paths.settings(REPO).exists())
        result = self.mason('project', 'add', REPO)
        self.assertEqual(result.returncode, 1)
        self.assertIn('give --workflow and --yes', result.stderr)


